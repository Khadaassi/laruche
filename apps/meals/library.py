@dataclass(frozen=True)
class LibraryRecipe:
    key: str
    name: str
    cuisine: str
    minutes: int
    tags: tuple
    ingredients: tuple
    steps: tuple

    @property
    def cuisine_label(self) -> str:
        return CUISINES[self.cuisine]


def r(key, name, cuisine, minutes, tags, ingredients, steps):
    return LibraryRecipe(key, name, cuisine, minutes, tuple(tags), tuple(ingredients), tuple(steps))


