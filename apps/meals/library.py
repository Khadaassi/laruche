"""Bibliothèque de recettes toutes prêtes (marocaines, françaises, italiennes, légères).

Recettes simples et rapides pour **4 personnes**, sans porc ni alcool. Les étiquettes
« sans gluten » / « sans lactose » signalent les recettes qui le sont naturellement
(vérifier les étiquettes des produits industriels : bouillon, épices…).
Une recette de la bibliothèque n'est qu'un modèle : « Ajouter à mes recettes » en fait
une copie modifiable dans la famille (`services.import_library`).

Format d'un ingrédient : (nom, quantité, unité) ; quantité None = à convenance.
Unités : voir `units.Unit` (piece, g, kg, ml, cl, l, tbsp, tsp, pack, can).
"""

from dataclasses import dataclass

